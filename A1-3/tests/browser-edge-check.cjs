const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({channel:'chrome',headless:true});
  const page = await browser.newPage({viewport:{width:390,height:844}});
  const checks=[];
  const violations=[];
  const config=JSON.parse(await fs.readFile('vercel.json','utf8'));
  const csp=config.headers[0].headers.find(h=>h.key==='Content-Security-Policy').value;
  await page.route('http://localhost:3000/', async route=>{const response=await route.fetch();await route.fulfill({response,headers:{...response.headers(),'content-security-policy':csp}})});
  await page.addInitScript(()=>{window.cspViolations=[];document.addEventListener('securitypolicyviolation',e=>window.cspViolations.push(e.violatedDirective))});
  await page.goto('http://localhost:3000/');
  await page.evaluate(()=>document.activeElement.blur());
  await page.keyboard.press('Control+Home');
  await page.keyboard.press('Tab');
  // Explicit focus verifies skip-link clipping and key access without a pointer.
  await page.locator('.skip-link').focus();
  assert.equal(await page.locator('.skip-link').evaluate(e=>getComputedStyle(e).clipPath),'none');
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'main');
  checks.push('Keyboard skip link reaches main; hidden skip link does not leak into full-page capture');
  await page.locator('[data-nav="relax"]').focus();
  await page.keyboard.press('Enter');
  await page.locator('#relax').waitFor({state:'visible'});
  await page.locator('input[name="course"][value="focus"]').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('input[name="course"][value="sleep"]').isChecked(),true);
  checks.push('Keyboard menu and native radio arrows');
  await page.locator('#open-player').click();
  await page.locator('#toggle-play').click();
  await page.waitForFunction(()=>!document.querySelector('#breathing-audio').paused);
  const before=await page.locator('#breath-orb').evaluate(e=>getComputedStyle(e).transform);
  await page.waitForTimeout(1200);
  const after=await page.locator('#breath-orb').evaluate(e=>getComputedStyle(e).transform);
  assert.notEqual(before,after);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('#breath-orb').evaluate(e=>getComputedStyle(e).transform),'none');
  assert.deepEqual(await page.evaluate(()=>window.cspViolations),[]);
  checks.push('Breath circle changes during playback and respects reduced motion; no Vercel CSP violations');
  await page.locator('[data-nav="care"]').click();
  for (const location of ['/dev_server.py','/.env','/README.md','/docs/service-plan.md','/%2e%2e/README.md','/api/recommend.py']) assert.equal((await page.request.get('http://localhost:3000'+location)).status(),404);
  checks.push('Local server blocks source, environment, docs, traversal, and API source files');
  await page.locator('input[name="environment"][value="집"]').check({force:true});
  await page.locator('#situation').fill('작업을 마치고 쉬고 싶어요.');
  await page.locator('#need').fill('긴장을 풀고 싶어요.');
  await page.route('**/api/recommend',()=>{});
  await page.locator('#recommend-button').click();
  assert.equal(await page.locator('#recommend-button').isDisabled(),true);
  await page.locator('[data-nav="about"]').click();
  await page.locator('[data-nav="care"]').click();
  assert.equal(await page.locator('#recommend-button').isEnabled(),true);
  assert.equal(await page.locator('#care-result').isVisible(),false);
  await page.unroute('**/api/recommend');
  checks.push('Leaving Care cancels a pending request and permits retry on return');
  await page.route('**/api/recommend',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify({course_id:'sleep',course:'편안한 수면 호흡',reason:'테스트용 모의 응답입니다. 실제 AI 추천이 아닙니다.'})}));
  await page.locator('#recommend-button').click();
  await page.locator('#care-result').waitFor({state:'visible'});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.screenshot({path:'docs/evidence/mobile-result-TEST-ONLY.png',fullPage:true});
  await page.unroute('**/api/recommend');
  await page.route('**/audio/focus.mp3',r=>r.abort());
  await page.locator('[data-nav="relax"]').click();
  await page.locator('input[name="course"][value="focus"]').check({force:true});
  await page.locator('#open-player').click();
  await page.locator('#toggle-play').click();
  await page.waitForFunction(()=>document.querySelector('#player-error').textContent.includes('불러오지'));
  assert.equal(await page.locator('#breathing-audio').evaluate(a=>a.paused),true);
  assert.equal(await page.locator('#toggle-play').isEnabled(),true);
  await page.unroute('**/audio/focus.mp3');
  await page.locator('#toggle-play').click();
  await page.waitForFunction(()=>!document.querySelector('#breathing-audio').paused && document.querySelector('#breathing-audio').currentTime>0.2);
  checks.push('Failed audio freezes the timer, shows guidance, and plays successfully after retry');
  await page.locator('.site-header .wordmark').click();
  await fs.writeFile('docs/evidence/additional-checks.json',JSON.stringify({actualAI:false,checks,status:'passed'},null,2));
  console.log(checks.join('\n'));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
